package io.github.xiaotong6666.uihelper.miuix.primitive

import androidx.compose.foundation.layout.WindowInsets
import androidx.compose.foundation.layout.WindowInsetsSides
import androidx.compose.foundation.layout.displayCutout
import androidx.compose.foundation.layout.navigationBars
import androidx.compose.foundation.layout.only
import androidx.compose.foundation.layout.union
import androidx.compose.foundation.layout.windowInsetsPadding
import androidx.compose.runtime.Composable
import androidx.compose.ui.Modifier

/**
 * MIUIX detail Scaffold owns the vertical insets but not landscape side cutouts/gesture bars.
 * Compose consumes insets already handled by parent containers, so this does not double-pad them.
 */
@Composable
fun Modifier.miuixDetailHorizontalInsets(): Modifier = windowInsetsPadding(
    WindowInsets.displayCutout.union(WindowInsets.navigationBars).only(WindowInsetsSides.Horizontal),
)
